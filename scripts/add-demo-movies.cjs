const prisma = new PrismaService();

async function main() {
  await prisma.$transaction(async tx => {
    for (const [title, description, year, duration, ageRating, name, actors, directors, unusual, franchise] of movies) {
      const existing = await tx.movie.findFirst({ where: { title: { equals: title, mode: 'insensitive' }, year } });
      if (existing) continue;
      const genre = await tx.genre.findFirst({ where: { name: { equals: name, mode: 'insensitive' } } });
      if (!genre) throw new Error(`Не найден жанр «${name}». Сначала примените миграции.`);
      await tx.movie.create({
        data: {
          title, description, year, duration, ageRating, genreId: genre.id,
          actors, directors: directors.split(','), unusual, franchise,
        },
      });
    }
  });
  console.log('Демонстрационный каталог готов.');
}

main()
  .catch(error => { console.error(error.message); process.exitCode = 1; })
  .finally(() => prisma.$disconnect());
